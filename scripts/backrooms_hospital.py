#!/usr/bin/env python3
"""Edit 30s of authentic filmed corridors with Blender's VSE in headless mode."""
import argparse
import glob
import json
import os
import shutil
import sys

import bpy


def main():
    tail=sys.argv[sys.argv.index("--")+1:] if "--" in sys.argv else []
    p=argparse.ArgumentParser()
    p.add_argument("--manifest",default="output/backrooms/sources_used.json")
    p.add_argument("--output-dir",default="output/backrooms")
    p.add_argument("--audio",default="output/backrooms/ambience.wav")
    a=p.parse_args(tail)
    manifest=json.load(open(a.manifest,encoding="utf-8"))
    if manifest["total_frames"]!=manifest["fps"]*30:
        raise RuntimeError("Expected a 30-second timeline")
    os.makedirs(a.output_dir,exist_ok=True)
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    scene=bpy.context.scene
    scene.render.resolution_x=manifest["width"]
    scene.render.resolution_y=manifest["height"]
    scene.render.resolution_percentage=100
    scene.render.fps=manifest["fps"]
    scene.frame_start=1
    scene.frame_end=manifest["total_frames"]
    scene.render.use_sequencer=True
    scene.view_settings.view_transform="Standard"
    scene.view_settings.look="Medium High Contrast"

    ed=scene.sequence_editor_create()
    seq=getattr(ed,"strips",None)
    if seq is None:
        seq=ed.sequences
    frame=1
    strips=[]
    for idx, shot in enumerate(manifest["shots"]):
        path=os.path.abspath(shot["file"])
        if not os.path.exists(path):
            raise RuntimeError("Missing processed live-action footage: "+path)
        strip=seq.new_movie("POV / "+shot["segment"],path,idx+1,frame)
        expected=int(shot["frames"])
        actual=strip.frame_final_duration
        if actual<expected:
            raise RuntimeError("Blender VSE clip too short {} < {}".format(actual,expected))
        if actual>expected:
            strip.frame_offset_end=actual-expected
        if idx>0:
            strip.blend_type="ALPHA_OVER"
            strip.blend_alpha=0.
            strip.keyframe_insert(data_path="blend_alpha",frame=frame)
            strip.blend_alpha=1.
            strip.keyframe_insert(data_path="blend_alpha",
                                  frame=frame+manifest["crossfade_frames"])
        else:
            strip.blend_type="REPLACE"
        strips.append(strip)
        frame+=expected-manifest["crossfade_frames"]
    if frame+manifest["crossfade_frames"]-1 != manifest["total_frames"]:
        # The first n-1 clips overlap with the next by the fade length.
        raise RuntimeError("Unexpected film duration arithmetic: "+str(frame))

    soundtrack=os.path.abspath(a.audio)
    if os.path.exists(soundtrack):
        sound=seq.new_sound("Hospital electricity + footsteps / original sound design",
                            soundtrack,len(strips)+2,1)
        strips.append(sound)
    scene.render.image_settings.file_format="FFMPEG"
    scene.render.ffmpeg.format="MPEG4"
    scene.render.ffmpeg.codec="H264"
    scene.render.ffmpeg.constant_rate_factor="MEDIUM"
    scene.render.ffmpeg.ffmpeg_preset="GOOD"
    scene.render.ffmpeg.audio_codec="NONE"
    outdir=os.path.abspath(a.output_dir)
    prefix=os.path.join(outdir,"blender_scene_")
    scene.render.filepath=prefix
    scene.render.use_file_extension=True

    # A portable blend with relative media links, shipped alongside normalized shots.
    project=os.path.join(outdir,"backrooms_hospital_edit.blend")
    bpy.context.preferences.filepaths.save_version=0
    bpy.ops.wm.save_as_mainfile(filepath=project)
    for strip in strips:
        if strip.type == "MOVIE":
            strip.filepath=bpy.path.relpath(os.path.abspath(strip.filepath))
        elif strip.type == "SOUND":
            strip.sound.filepath=bpy.path.relpath(os.path.abspath(strip.sound.filepath))
    bpy.ops.wm.save_as_mainfile(filepath=project)
    scene.frame_set(1)
    print("BLENDER_HOSPITAL_EDIT_PROJECT",project,flush=True)
    print("START_BLENDER_HOSPITAL_RENDER",scene.frame_end,flush=True)
    bpy.ops.render.render(animation=True)
    candidate=sorted(glob.glob(prefix+"*.mp4"),key=os.path.getmtime,reverse=True)
    if not candidate:
        raise RuntimeError("No H264 movie generated by Blender VSE")
    final=os.path.join(outdir,"backrooms_silent.mp4")
    shutil.move(candidate[0],final)
    if os.path.getsize(final)<100000:
        raise RuntimeError("H264 film too small to be valid")
    print("BLENDER_POV_RENDER_COMPLETE",final,os.path.getsize(final),flush=True)


if __name__=="__main__":
    main()
